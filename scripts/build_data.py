"""Build data/awardees.js, data/international.js, JSON and CSV from the working files.

Usage: python3 scripts/build_data.py <workdir-with-final.json-and-intl.json>
"""
import json, csv, sys, os

W = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data")

XPOSTS = {
    "s2026-38": "https://x.com/EduMinOfIndia/status/2096143563499458932",
    "s2026-36": "https://x.com/EduMinOfIndia/status/2096121360259154243",
    "s2026-47": "https://x.com/EduMinOfIndia/status/2096154123246916018",
    "s2026-41": "https://x.com/EduMinOfIndia/status/2096142815311081925",
    "s2026-19": "https://x.com/EduMinOfIndia/status/2096135957091160492",
}

rows = json.load(open(os.path.join(W, "final.json")))
out = []
for r in rows:
    o = dict(
        id=r["id"], cat=r["cat"], year=r["year"], name=r["name"], role=r.get("role", ""),
        disc=r.get("disc", ""), school=r.get("school", ""), addr=r.get("addr", ""),
        state=r.get("state", ""), org=r.get("org", ""), photo=r.get("photo", ""),
        cit=r.get("citation", ""), core=r.get("core", ""), cs=r.get("cit_status", ""),
        src=r.get("cit_src", ""), yt=r.get("yt", {}), x=XPOSTS.get(r["id"], ""),
    )
    if "t_en" in r:
        o.update(t=[r["t_en"], r["t_hi"]], s_hi=r["s_hi"], th=r["themes"], sub=r["subj"],
                 gr=r["grades"], cost=r["cost"], st=[r["steps_en"], r["steps_hi"]], scene=r["scene"])
    out.append(o)

intl = json.load(open(os.path.join(W, "intl.json")))

def dump_js(name, var, obj):
    with open(os.path.join(D, name), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/build_data.py — edit the JSON and rebuild. */\n")
        f.write(f"window.{var} = ")
        json.dump(obj, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

dump_js("awardees.js", "NAT_DATA", out)
dump_js("international.js", "INTL_DATA", intl)
json.dump(out, open(os.path.join(D, "awardees.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
json.dump(intl, open(os.path.join(D, "international.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

with open(os.path.join(D, "awardees.csv"), "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["id", "category", "year", "name", "role/discipline", "school/institution", "state", "organisation",
                "practice (English)", "practice (Hindi)", "themes", "subjects", "class band", "cost (0 zero,1 low,2 needs funds)",
                "citation status", "official core area", "youtube", "x post", "source"])
    for o in out:
        yt = o["yt"]
        ytu = f"https://www.youtube.com/watch?v={yt['id']}" + (f"&list={yt['list']}&index={yt['index']}" if yt.get("list") and yt.get("index") else "") if yt.get("id") else ""
        w.writerow([o["id"], o["cat"], o["year"], o["name"], o["role"] or o["disc"], o["school"], o["state"], o["org"],
                    o.get("t", ["", ""])[0], o.get("t", ["", ""])[1], ";".join(o.get("th", [])), ";".join(o.get("sub", [])),
                    ";".join(o.get("gr", [])), o.get("cost", ""), o["cs"], o["core"], ytu, o["x"], o["src"]])
print(len(out), "awardees;", len(intl["practices"]), "international practices;", len(intl["gtp"]), "GTP winners")
