"""Build data/curriculum.js: NCERT chapters / CGs (from data/working/curriculum_src.py) plus the
hand-assigned topic list of every analysed school practice (data/working/practice_topics.txt).

Usage: python3 scripts/build_curriculum.py
"""
import json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "data", "working"))
import curriculum_src as C  # noqa: E402

def manual_topics():
    """Hand-assigned practice topics from data/working/practice_topics.txt ("id: t1,t2")."""
    out = {}
    for line in open(os.path.join(ROOT, "data", "working", "practice_topics.txt"), encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        pid, _, tps = line.partition(":")
        out[pid.strip()] = [x.strip() for x in tps.split(",") if x.strip()]
    return out


def main():
    aw = json.load(open(os.path.join(ROOT, "data", "awardees.json"), encoding="utf-8"))
    ptop = manual_topics()
    ids = {r["id"] for r in aw if r.get("t") and r["cat"] == "school"}
    bad = sorted(set(ptop) - ids) + [t for v in ptop.values() for t in v if t not in C.TOPICS]
    assert not bad, f"unknown ids/topics: {bad}"
    missing = sorted(ids - set(ptop))
    if missing:
        print("WARNING: practices without a topic line:", missing)
    books = [dict(cls=c, subj=s, book=b, code=code, ch=[dict(n=i + 1, t=t, tp=tp) for i, (t, tp) in enumerate(chs)])
             for (c, s, b, code, chs) in C.BOOKS]
    cur = dict(topics=C.TOPICS, subjects=C.SUBJECTS, books=books, langBooks=C.LANG_BOOKS, langSkills=C.LANG_SKILLS,
               cg={k: [dict(cg=a, code=b, d=d, tp=tp) for (a, b, d, tp) in v] for k, v in C.CG.items()},
               worldTopics=C.WORLD_TOPICS, practiceTopics=ptop)
    with open(os.path.join(ROOT, "data", "curriculum.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/build_curriculum.py */\nwindow.CUR_DATA = ")
        json.dump(cur, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    cnt = collections.Counter(t for v in ptop.values() for t in v)
    print(len(ptop), "practices tagged;", sum(1 for v in ptop.values() if not v), "with no topic")
    print(sorted(cnt.items(), key=lambda x: -x[1]))
    used = {t for b in books for ch in b["ch"] for t in ch["tp"]} | {t for v in C.CG.values() for x in v for t in x[3]}
    print("topics used by chapters/CG but no practice:", [t for t in used if not cnt.get(t)])
    print("chapters:", sum(len(b["ch"]) for b in books))


if __name__ == "__main__":
    main()
